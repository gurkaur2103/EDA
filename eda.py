import re

def convert_duration(x):

    if pd.isna(x):
        return np.nan

    x = str(x).lower()

    # Months
    month_match = re.search(r'(\d+)\s*month', x)

    if month_match:
        months = int(month_match.group(1))

        # Approximation:
        # 1 month ≈ 30 days × 2 study hours/day
        return months * 60

    # Weeks
    week_match = re.search(r'(\d+)\s*week', x)

    if week_match:
        weeks = int(week_match.group(1))
        return weeks * 14

    # Hours
    hour_match = re.search(r'(\d+)\s*h', x)

    mins_match = re.search(r'(\d+)\s*m', x)

    hours = int(hour_match.group(1)) if hour_match else 0
    mins  = int(mins_match.group(1)) if mins_match else 0

    return hours + mins / 60

