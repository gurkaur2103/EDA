# Convert duration into minutes
if 'duration' in skillshare.columns:

    def convert_duration(x):

        if pd.isna(x):
            return np.nan

        x = str(x).lower()

        hours = 0
        mins = 0

        if 'h' in x:
            try:
                hours = int(x.split('h')[0].strip())
            except:
                pass

        if 'm' in x:
            try:
                mins = int(
                    x.split('h')[-1]
                    .replace('m', '')
                    .strip()
                )
            except:
                pass

        return hours * 60 + mins

    skillshare['duration_min'] = skillshare['duration'].apply(convert_duration)

